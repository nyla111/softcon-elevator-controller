"""Direct-call APIs between parts. Owned by: Tech lead.

Use the bus for "something happened"; use these calls only when you need an
answer back immediately. Each Protocol is implemented by exactly one part.
Until it exists, ems.core.app.build() fills it with the stub in contracts/stubs.py.
"""
from __future__ import annotations

from typing import Optional, Protocol

from .types import (Call, CallId, CarId, CarState, CarStatus, CredentialId,
                    Floor, GroupId, Mode, Permission)


class ControllerAdapter(Protocol):          # Part 1 (simulator implements it)
    """Supervisory commands. Controllers may refuse any command (C-01) -> False."""
    def status(self, car_id: CarId) -> CarStatus: ...
    def all_status(self, group: Optional[GroupId] = None) -> list[CarStatus]: ...
    def register_stop(self, car_id: CarId, floor: Floor, call_id: CallId) -> bool: ...
    def cancel_stop(self, car_id: CarId, call_id: CallId) -> bool: ...
    def park(self, car_id: CarId, floor: Floor) -> bool: ...
    def set_standby(self, car_id: CarId, on: bool) -> bool: ...
    def set_independent_service(self, car_id: CarId, on: bool) -> bool: ...
    def close_to_new_calls(self, car_id: CarId, on: bool) -> bool: ...
    def express(self, car_id: CarId, floor: Floor, hold_doors_open: bool = False) -> bool: ...


class AcsClient(Protocol):                  # Part 1 (mock ACS device)
    """Raises TimeoutError when the simulated ACS is down or slower than 1 s."""
    def lookup(self, credential_id: CredentialId) -> Permission: ...
    def issue_visitor_pass(self, tenant_id: str, floors: set[Floor],
                           valid_from: float, valid_to: float,
                           group_size: int = 1) -> CredentialId: ...
    def revoke(self, credential_id: CredentialId) -> None:   # NFR-SE6
        """Revoked credentials answer valid=False from now on."""
        ...


class AccessService(Protocol):              # Part 3
    def permission(self, credential_id: CredentialId) -> Permission: ...
    def public_floors(self, at_time: float) -> set[Floor]: ...


class CarStates(Protocol):                  # Part 4 (only writer of car state)
    def state(self, car_id: CarId) -> CarState: ...
    def request(self, car_id: CarId, new: CarState, by: str) -> bool:
        """Grant only if BR-06 allows it. Returns False if refused."""
        ...
    def release(self, car_id: CarId, from_state: CarState, by: str) -> bool:
        """Leave a state you hold (e.g. VIP_EXCLUSIVE -> GROUP_SERVICE)."""
        ...
    def dispatchable(self, group: GroupId) -> list[CarId]: ...
    def safety_active(self) -> bool:
        """True during fire recall / emergency power: no ordinary dispatch."""
        ...


class Dispatcher(Protocol):                 # Part 2
    def current_mode(self, group: GroupId) -> Mode: ...
    def predicted_wait(self, call_id: CallId) -> float: ...
    def reassign_calls_of(self, car_id: CarId, reason: str) -> list[CallId]: ...
    def pending_calls(self, group: GroupId) -> list[Call]: ...
    def would_breach_ceiling_without(self, car_id: CarId) -> bool:
        """Used by Part 5 (VIP FR-72, goods move FR-36): True if removing the
        car pushes any waiting call's elapsed + ETA over the mode ceiling."""
        ...


class DispatchEngine(Protocol):             # Part 2, replaceable plug-in (FR-06)
    def choose_car(self, call: Call, cars: list[CarStatus], mode: Mode) -> Optional[CarId]: ...


class Database(Protocol):                   # Part 1 (trip database with buffering, FR-107)
    def write(self, record: dict) -> None:
        """Never raises and never blocks; buffers in memory while the database is down."""
        ...
    def records(self) -> list[dict]:
        """Persisted records only (not the ones still in the buffer)."""
        ...
    def available(self) -> bool: ...


class Notifier(Protocol):                   # Part 1 (email/SMS test inbox)
    def send(self, recipients: list[str], subject: str, body: str) -> None: ...
